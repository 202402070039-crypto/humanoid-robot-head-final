# SELECTIVE KNOWLEDGE RETRIEVAL
# ============================================================

def get_knowledge(categories):
    """
    Return only the robot self-knowledge
    required for the requested categories.
    """

    if not categories:
        return ""

    selected = []

    for category in categories:

        if category in ROBOT_KNOWLEDGE:

            selected.append(
                f"[{category}]\n"
                + ROBOT_KNOWLEDGE[category].strip()
            )

    return "\n\n".join(selected)
