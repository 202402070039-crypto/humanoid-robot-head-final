# ============================================================
# ROUTER
# ============================================================

def classify_question(user_text):
    """
    Semantic router for robot self-knowledge.

    This function does NOT answer the question.
    It only determines:
        - whether the question is about Master
        - which knowledge categories are needed
        - whether live CV is required
        - whether person information is required
    """

    question = (user_text or "").strip()

    if not question:
        return {
            "is_self": False,
            "categories": [],
            "needs_live_cv": False,
            "needs_person": False
        }

    # --------------------------------------------------------
    # Keep the router prompt intentionally small.
    # --------------------------------------------------------

    system_prompt = """
You are the intent router for a humanoid robot named Master.

Your task is ONLY to classify the user's question.
Do NOT answer the question.

"is_self" means:
The user is asking about Master, Master's hardware,
software, abilities, sensors, movement, languages,
architecture, or how Master works.

Examples of SELF questions:
- What is your name?
- Who made you?
- Which languages can you speak?
- What camera do you have?
- How many servos do you have?
- How do your eyes follow me?
- Can you see me?
- Do you recognize me?
- What can you do?

Examples of NOT SELF questions:
- What is the capital of India?
- What is today's weather?
- What is the latest news?
- What is 25 times 48?

Use ONLY these categories:

identity
language
audio
speech
camera
vision
face_recognition
object_detection
people_tracking
head_tracking
eyes
neck
jaw
servos
raspberry_pi
esp32
mqtt
ai
memory
capabilities

Category meanings:

identity = robot name, creator, purpose
language = languages and language detection
audio = microphone and hearing
speech = speaking and TTS
camera = camera hardware and location
vision = computer vision system
face_recognition = recognizing or enrolling faces
object_detection = detecting objects
people_tracking = detecting/counting/tracking people
head_tracking = face position, head direction, tilt, gaze
eyes = eye movement and eye tracking
neck = neck/head movement
jaw = jaw movement and speech synchronization
servos = servo architecture
raspberry_pi = Raspberry Pi
esp32 = ESP32
mqtt = MQTT communication
ai = AI and conversation
memory = conversation/face memory
capabilities = overall abilities

Live CV:
Set needs_live_cv=true when the question requires information
about what the camera currently sees or is currently doing.

Examples:
"Can you see me?" -> true
"Do you recognize me?" -> true
"What objects can you see?" -> true
"How many people are here?" -> true

Person information:

Set needs_person=true ONLY when information about the currently
recognized person is required.

Examples:

"Can you see me?"
-> needs_person=false

"Are you looking at me?"
-> needs_person=false

"Do you recognize me?"
-> needs_person=true

"What is my name?"
-> needs_person=true
IMPORTANT:
The word "me" by itself does NOT mean needs_person=true.

Questions about whether the robot can currently see, look at,
detect, or track the user require live CV but do not require
person information.

Only questions involving identity, recognition, name, or known-person
information require needs_person=true.
IMPORTANT:
A question such as "How do your eyes follow me?"
is about Master's architecture, NOT about the current identity
of the person.

Return ONLY JSON with exactly these fields:

{
  "is_self": true or false,
  "categories": ["category1", "category2"],
  "needs_live_cv": true or false,
  "needs_person": true or false
}
"""

    user_prompt = f"""
Classify this user question:

{question}
"""

    try:

        response = client.chat.completions.create(
            model="openai/gpt-oss-20b",

            messages=[
                {
                    "role": "system",
                    "content": system_prompt
                },
                {
                    "role": "user",
                    "content": user_prompt
                }
            ],

            response_format={
                "type": "json_object"
            },

            temperature=0,

            max_completion_tokens=300
        )

        content = (
            response
            .choices[0]
            .message
            .content
        )

        print(
            "[SELF ROUTER RAW]",
            repr(content)
        )

        result = json.loads(content)

        # ----------------------------------------------------
        # VALIDATE
        # ----------------------------------------------------

        is_self = bool(
            result.get(
                "is_self",
                False
            )
        )

        categories = result.get(
            "categories",
            []
        )

        if not isinstance(
            categories,
            list
        ):
            categories = []

        # Only allow categories that actually exist
        # in our knowledge database.
        categories = [
            category
            for category in categories
            if category in ROBOT_KNOWLEDGE
        ]

        needs_live_cv = bool(
            result.get(
                "needs_live_cv",
                False
            )
        )

        needs_person = bool(
            result.get(
                "needs_person",
                False
            )
        )

        # Non-self questions cannot request robot
        # knowledge or live robot information.
        if not is_self:

            categories = []

            needs_live_cv = False

            needs_person = False

        final_result = {
            "is_self": is_self,
            "categories": categories,
            "needs_live_cv": needs_live_cv,
            "needs_person": needs_person
        }

        print(
            "[SELF ROUTER]",
            final_result
        )

        return final_result

    except Exception as e:

        print(
            "[SELF ROUTER] Error:",
            e
        )

        return {
            "is_self": False,
            "categories": [],
            "needs_live_cv": False,
            "needs_person": False
        }